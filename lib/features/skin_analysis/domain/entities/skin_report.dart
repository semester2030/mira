class SkinReport {
  final String skinType;
  final int wrinkles;
  final int spots;
  final int hydration;
  final int oiliness;
  final int pores;
  final String advice;

  SkinReport({
    required this.skinType,
    required this.wrinkles,
    required this.spots,
    required this.hydration,
    required this.oiliness,
    required this.pores,
    required this.advice,
  });
}
